public class Switch {
    public static void main(String[] args){
        //switch 

        int i=9;

        switch(i){ //! switch(expression)--> result must be in byte short int char {enumeration}
            case 1:
            System.out.println("i is one ");
            break; // ?Break statement to control the conditions region  ?

            case 2:

            System.out.println("i is two");
            break;

            case 3:

            System.out.println("i is threee");

            break;

            default:
                System.out.println("i is greater than three");
                break;

        }

    }

    
}
